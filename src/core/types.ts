import type { Options, SvgMapObject } from '@/types'

export class Types {
  private _svgs: Map<string, SvgMapObject>
  private _options: Options

  constructor(svgs: Map<string, SvgMapObject>, options: Options) {
    this._svgs = svgs
    this._options = options
  }

  /**
   * Generate TypeScript type definition string
   * @returns TypeScript type definition content
   */
  public generate(): string {
    if (!this._options.types)
      return ''

    const iconIds = Array.from(this._svgs.values())
      .map(svg => svg.id)
      .sort()

    const prefix = this._options.prefix || ''
    const prefixComment = prefix ? ` * Prefix: '${prefix}'` : ' * Prefix: none'
    const typeName = 'Icons'

    if (iconIds.length === 0) {
      return `// Generated by vite-plugin-svg-spritemap
/**
${prefixComment}
 */

export type ${typeName} = never;
export type ${typeName}Prefix = ${prefix ? `'${prefix}'` : '\'\''};
export type ${typeName}Prefixed = never;
`
    }

    const unionType = iconIds
      .map(id => `'${id}'`)
      .join(' | ')

    return `// Generated by vite-plugin-svg-spritemap
/**
${prefixComment}
 */

export type ${typeName} = ${unionType};
export type ${typeName}Prefix = ${prefix ? `'${prefix}'` : '\'\''};
export type ${typeName}Prefixed = \`\${${typeName}Prefix}\${${typeName}}\`;
`
  }
}
